// Generates supabase/migrations/20261025000000_seed_test_listings.sql from src/lib/data.ts RESTAURANTS.
// Run: node scripts/gen-seed-listings-sql.mjs
import { createJiti } from "jiti";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const jiti = createJiti(import.meta.url, { alias: { "@": path.join(root, "src") } });
const { RESTAURANTS } = await jiti.import(path.join(root, "src/lib/data.ts"));

const q = (v) =>
  v === null || v === undefined || v === ""
    ? "null"
    : typeof v === "number"
      ? (Number.isFinite(v) ? String(v) : "null")
      : `'${String(v).replace(/'/g, "''")}'`;
const COLS = ["id","name","slug","city","neighborhood","cuisine","tagline","story","hours","address","lat","lng","emoji","accent"];
const rows = RESTAURANTS.map((r) => `  (${COLS.map((c) => q(r[c])).join(", ")}, true, false, true, 'seed')`);

const sql = `-- GENERATED by scripts/gen-seed-listings-sql.mjs from src/lib/data.ts (RESTAURANTS). Do not hand-edit.
-- Seeds every app-catalog restaurant into public.listings as a TEST listing (${RESTAURANTS.length} rows),
-- so favorites / Will try / redeem can reference them without on-the-fly listing writes.
-- Ordered before 20261026000000_member_loved_restaurants.sql. Idempotent.

alter table public.listings add column if not exists is_test boolean not null default false;
alter table public.listings add column if not exists source text;

insert into public.listings
  (${COLS.join(", ")}, approved, banned, is_test, source)
values
${rows.join(",\n")}
on conflict (id) do update
  -- Existing rows keep their content, approval and any deleted marker; only tag them as test/seed.
  set is_test = true,
      source = coalesce(public.listings.source, 'seed');

create index if not exists listings_is_test_idx on public.listings (is_test) where is_test;

-- CLEANUP (when real restaurants launch). Review first:
--   select id, name from public.listings where is_test;
-- Deleting cascades (on delete cascade) to member_favorites and member_loved_restaurants rows,
-- and to other listing_* tables that reference listings with cascade; profiles.restaurant_id is set null.
-- reward_ledger / plate_reviews (restaurant_id is plain text, no FK) are NOT removed.
--   delete from public.listings where is_test;
`;
writeFileSync(path.join(root, "supabase/migrations/20261025000000_seed_test_listings.sql"), sql);
console.log(`rows=${RESTAURANTS.length}`);
